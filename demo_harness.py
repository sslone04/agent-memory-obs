"""Labeled, reversible failure injection for the Memory Health demo.

Every row this script writes carries an agent_id prefixed 'demo-', so the whole
demo is removable with one predicate.  Nothing here simulates a failure: the
records, embeddings, retrievals and similarity scores are all real, produced by
the same code paths production uses.  The only thing that is staged is *which*
data goes in.

    python demo_harness.py seed
    python demo_harness.py inject degradation
    python demo_harness.py heal degradation
    python demo_harness.py timeline --hours 6
    python demo_harness.py reset

Add --pause to stop before each phase so a narrator can catch up.
"""

