def require_demo(agent_id: str) -> str:
    """No row leaves this module without a demo- prefix on its agent_id."""
    if not agent_id.startswith(DEMO_PREFIX):
        raise ValueError(
            f"refusing to touch agent_id {agent_id!r}: "
            f"demo_harness only writes agent ids prefixed {DEMO_PREFIX!r}"
        )
    return agent_id


def protected_counts(conn: psycopg.Connection) -> dict[str, int]:
    """Row counts for everything that is NOT demo data.

    coalesce() matters: health events can carry a NULL agent_id, and those are
    real check results that must be counted as protected.
    """
    counts = {}
    with conn.cursor() as cur:
        for table in TABLES:
            cur.execute(
                f"SELECT count(*) AS n FROM {table} "
                f"WHERE coalesce(agent_id, '') NOT LIKE %s",
                (DEMO_LIKE,),
            )
            counts[table] = cur.fetchone()["n"]
    return counts


def assert_untouched(before: dict[str, int], after: dict[str, int]) -> None:
    for table, n in before.items():
        if after[table] != n:
            raise RuntimeError(
                f"SAFETY VIOLATION: {table} non-demo rows changed "
                f"{n} -> {after[table]}. Aborting."
            )


def demo_counts(conn: psycopg.Connection) -> dict[str, int]:
    counts = {}
    with conn.cursor() as cur:
        for table in TABLES:
            cur.execute(
                f"SELECT count(*) AS n FROM {table} WHERE agent_id LIKE %s",
                (DEMO_LIKE,),
            )
            counts[table] = cur.fetchone()["n"]
    return counts


