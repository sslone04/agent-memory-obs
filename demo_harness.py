def phase(title: str, detail: str = "") -> None:
    print()
    print("─" * 74)
    print(f"  {title}")
    if detail:
        for line in textwrap.wrap(detail, 70):
            print(f"  {line}")
    print("─" * 74)
    if PAUSE:
        try:
            input("  [enter to run this phase, ctrl-c to stop] ")
        except (EOFError, KeyboardInterrupt):
            print("\n  stopped.")
            sys.exit(0)


def step(message: str) -> None:
    print(f"    {message}")


