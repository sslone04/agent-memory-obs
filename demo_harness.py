def summarise(conn: psycopg.Connection) -> None:
    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT count(*) AS retrievals,
                   count(*) FILTER (
                       WHERE results_returned = 0 AND coalesce(raw_candidates, 0) > 0
                   ) AS floored
            FROM memory_retrievals
            WHERE extract(epoch FROM (now() - retrieved_at)) <= 3600
            """
        )
        window = cur.fetchone()
    counts = demo_counts(conn)
    print()
    print("  demo rows:", ", ".join(f"{t.split('_', 1)[1]}={n}" for t, n in counts.items()))
    rate = (
        100.0 * window["floored"] / window["retrievals"] if window["retrievals"] else 0.0
    )
    print(
        f"  last 60m: {window['retrievals']} retrievals, "
        f"{window['floored']} floored out ({rate:.1f}%)"
    )
    print("  dashboard: http://127.0.0.1:8000")


def main(argv: list[str] | None = None) -> int:
    global PAUSE
    parser = argparse.ArgumentParser(
        description="Labeled, reversible failure injection for the Memory Health demo."
    )
    parser.add_argument("--pause", action="store_true", help="stop before each phase")
    sub = parser.add_subparsers(dest="mode", required=True)

    p_seed = sub.add_parser("seed", help="write the demo corpus + a healthy baseline")
    p_seed.add_argument("--recalls", type=int, default=8)

    p_inject = sub.add_parser("inject", help="introduce one failure class for real")
    p_inject.add_argument(
        "failure", choices=("stale", "eviction", "degradation", "near_miss", "drift")
    )
    p_inject.add_argument("--count", type=int, default=None)

    p_heal = sub.add_parser("heal", help="reverse an injected condition")
    p_heal.add_argument(
        "failure", nargs="?", default="all",
        choices=("all", "stale", "eviction", "degradation", "near_miss", "drift"),
    )

    p_reset = sub.add_parser("reset", help="delete every demo- row")
    p_reset.add_argument("--yes", action="store_true", help="skip the confirmation")

    sub.add_parser("story", help="the full arc: healthy -> warn -> blind -> recovered")

    p_time = sub.add_parser("timeline", help="seed -> healthy -> degrade -> heal")
    p_time.add_argument("--hours", type=int, default=6)
    p_time.add_argument("--buckets", type=int, default=6)
    p_time.add_argument("--per-bucket", type=int, default=4)

    args = parser.parse_args(argv)
    PAUSE = args.pause
    random.seed(20260808)

    with connect() as conn:
        if args.mode == "seed":
            do_seed(conn, recalls=args.recalls)
        elif args.mode == "inject":
            if args.failure == "stale":
                inject_stale(conn, count=args.count or 6)
            elif args.failure == "eviction":
                inject_eviction(conn, count=args.count or 8)
            elif args.failure == "degradation":
                inject_degradation(conn, count=args.count or 10)
            elif args.failure == "near_miss":
                inject_near_miss(conn, count=args.count or 9)
            else:
                inject_drift(conn)
        elif args.mode == "heal":
            do_heal(conn, which=args.failure)
        elif args.mode == "reset":
            do_reset(conn, assume_yes=args.yes)
        elif args.mode == "story":
            do_story(conn)
        elif args.mode == "timeline":
            do_timeline(
                conn, hours=args.hours, buckets=args.buckets, per_bucket=args.per_bucket
            )
        summarise(conn)
    return 0


if __name__ == "__main__":
    sys.exit(main())
